#две ф-ии одна генерирует все числа с лидирующими нулями в двоичной системе счисления
#вторая делает тоже самое только в n-ричной системе счисленися n<=10
#на вход фии дается len(двоичное число)
from itertools import product
def lt(lst):
    for x in product('01', repeat = len(lst)):
        s = ''.join(x)
        print(s)

lt('100000')